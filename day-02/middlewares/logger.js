// ১. রিকোয়েস্ট লগার মিডলওয়্যার (Request Logger)
// প্রতিটি রিকোয়েস্ট কোন মেথডে এবং কোন URL এ এসেছে তা কনসোলে প্রিন্ট করবে
export const requestLogger = (req, res, next) => {
  const timestamp = new Date().toLocaleTimeString();
  console.log(`[${timestamp}] 📢 [LOG] Method: ${req.method} | URL: ${req.url}`);

  // ⚠️ খুব গুরুত্বপূর্ণ:
  // next() কল না করলে রিকোয়েস্ট এখানেই আটকে থাকবে, পরের ধাপে (পরের মিডলওয়্যার বা কন্ট্রোলারে) যাবে না!
  next();
};

// ২. একটি সাধারণ সিকিউরিটি / চেক মিডলওয়্যার উদাহরণ
export const checkApiKey = (req, res, next) => {
  // উদাহরণস্বরূপ: হেডারে কোনো বিশেষ সিক্রেট কি আছে কিনা চেক করা
  // (শেখার সুবিধার্থে আমরা আপাতত সবার জন্য উন্মুক্ত রাখলাম)
  next();
};
